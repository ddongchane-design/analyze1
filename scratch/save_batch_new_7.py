import sys
import json
from pathlib import Path

# Add project root to sys.path
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.append(str(project_root))

from agents.harness import validate_item

def save_and_delete(video_id, primary_topic, secondary_topics, tags, analysis_data):
    pending_path = project_root / "data" / "pending" / f"{video_id}.json"
    if not pending_path.exists():
        print(f"Warning: {pending_path.name} does not exist in pending.")
        return
        
    pending_data = json.loads(pending_path.read_text(encoding="utf-8"))
    video_data = pending_data["video"]
    
    classification_data = {
        "primary_topic": primary_topic,
        "secondary_topics": secondary_topics,
        "tags": tags
    }
    
    final_data = {
        "video": video_data,
        "analysis": analysis_data,
        "classification": classification_data
    }
    
    # Run the validation harness
    is_valid, errors = validate_item(final_data, project_root)
    if not is_valid:
        print(f"Error: {video_id} failed harness validation:")
        for err in errors:
            print(f"  - {err}")
        return
        
    analyzed_dir = project_root / "data" / "analyzed" / primary_topic
    analyzed_dir.mkdir(parents=True, exist_ok=True)
    
    result_path = analyzed_dir / f"{video_id}.json"
    result_path.write_text(json.dumps(final_data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Saved: {result_path.relative_to(project_root)}")
    
    pending_path.unlink()
    print(f"Deleted pending: {pending_path.relative_to(project_root)}")

